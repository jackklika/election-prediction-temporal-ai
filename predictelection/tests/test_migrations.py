"""The migrations and the models must describe the same schema.

Two paths build this database: `create_all`, which the tests use because it is
fast against an empty database, and Alembic, which is the only one that works
against a database with data in it. If they drift, every test passes against a
schema production does not have.

`create_all` cannot alter an existing CHECK constraint or enum. Adding a
predicate kind or a constraint branch to a live database through it silently
does nothing, which is the specific failure this suite exists to make loud.

Runs against a scratch database of its own. Migrating the suite's database
mid-run would leave later tests depending on whatever state this left behind.
"""

from __future__ import annotations

import os
from pathlib import Path

from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.script import ScriptDirectory
import pytest
import sqlalchemy as sa

from predictelection.sql import Base
from predictelection.sql.schema import include_object


pytestmark = pytest.mark.postgres


SCRATCH_DATABASE = "predictelection_migrations_test"
_ROOT = Path(__file__).resolve().parents[2]


def _alembic_config(url: str) -> Config:
    config = Config(str(_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(_ROOT / "alembic"))
    config.cmd_opts = None
    config.set_main_option("sqlalchemy.url", url)
    return config


@pytest.fixture
def migrated_engine(postgres_engine: sa.Engine):
    """A database built only by `alembic upgrade head`.

    Created and dropped around the test so nothing it does can reach the
    schema the rest of the suite is using.
    """

    admin_url = postgres_engine.url.set(database="postgres")
    admin = sa.create_engine(admin_url, isolation_level="AUTOCOMMIT")
    scratch_url = postgres_engine.url.set(database=SCRATCH_DATABASE)

    with admin.connect() as connection:
        connection.execute(sa.text(f'DROP DATABASE IF EXISTS "{SCRATCH_DATABASE}"'))
        connection.execute(sa.text(f'CREATE DATABASE "{SCRATCH_DATABASE}"'))

    engine = sa.create_engine(scratch_url, connect_args={"options": "-c timezone=utc"})
    try:
        from alembic import command

        # env.py reads this rather than PostgresConfig, so the migration lands
        # on the scratch database instead of the configured one.
        os.environ["POSTGRES_URL"] = scratch_url.render_as_string(hide_password=False)
        command.upgrade(_alembic_config(os.environ["POSTGRES_URL"]), "head")
        yield engine
    finally:
        os.environ.pop("POSTGRES_URL", None)
        engine.dispose()
        with admin.connect() as connection:
            connection.execute(
                sa.text(f'DROP DATABASE IF EXISTS "{SCRATCH_DATABASE}" WITH (FORCE)')
            )
        admin.dispose()


def test_migrations_produce_the_schema_the_models_declare(
    migrated_engine: sa.Engine,
) -> None:
    """A migrated database and Base.metadata must be indistinguishable.

    compare_metadata is what `--autogenerate` uses, so an empty diff here means
    the next autogenerated revision would also be empty — that is, nothing has
    been changed in the models without a migration to match.
    """

    with migrated_engine.connect() as connection:
        context = MigrationContext.configure(
            connection,
            opts={
                "compare_type": True,
                "compare_server_default": True,
                # The same filter env.py uses, or this passes for the wrong
                # reason: the scratch database has no PostGIS, so it would not
                # see the sixty tiger-geocoder tables the real one has.
                "include_object": include_object,
            },
        )
        differences = [
            difference
            for difference in compare_metadata(context, Base.metadata)
            # Alembic's own bookkeeping table is not in Base.metadata by design.
            if "alembic_version" not in str(difference)
        ]

    assert differences == [], (
        "the models and the migrations disagree. Run "
        '`make migration MESSAGE="..."` and read what it generates.'
    )


def test_autogenerate_leaves_other_extensions_tables_alone(
    postgres_engine: sa.Engine,
) -> None:
    """PostGIS installs some sixty tables of its own into this database.

    Without a filter, autogenerate reflects them, finds them missing from
    Base.metadata and proposes DROP TABLE for each — a migration that would
    dismantle the extension. Checked against the real database rather than the
    scratch one, because the scratch one has no PostGIS to get wrong.
    """

    with postgres_engine.connect() as connection:
        context = MigrationContext.configure(
            connection,
            opts={
                "compare_type": True,
                "compare_server_default": True,
                "include_object": include_object,
            },
        )
        differences = [
            difference
            for difference in compare_metadata(context, Base.metadata)
            if "alembic_version" not in str(difference)
        ]

    dropped = [
        difference
        for difference in differences
        if isinstance(difference, tuple) and str(difference[0]).startswith("remove_")
    ]
    assert dropped == [], f"autogenerate would drop tables it does not own: {dropped}"


def test_there_is_exactly_one_head() -> None:
    """Two heads mean two branches, and `upgrade head` stops being unambiguous.

    Cheap to check and easy to create by accident: two revisions generated from
    the same parent on different branches both claim to be the tip.
    """

    script = ScriptDirectory.from_config(_alembic_config("postgresql://unused"))
    assert len(script.get_heads()) == 1, script.get_heads()
