"""Building the schema, and telling Alembic which parts of it are ours.

`create_schema` is for tests and local setup, where the database is empty and
speed matters. It is not a migration path: `create_all` cannot alter an existing
CHECK constraint or enum, so a new predicate kind applied through it against a
live database silently does nothing. Anything with data in it goes through
Alembic.
"""

from __future__ import annotations

from typing import Any

from sqlalchemy import Engine, text
from sqlalchemy.orm import Session

from predictelection.sql.base import Base
from predictelection.sql.namespace import seed_identifier_namespaces
from predictelection.sql.predicate import seed_predicates


def create_schema(engine: Engine) -> None:
    """Create all registered tables and seed immutable predicate contracts."""

    with engine.begin() as connection:
        # Before create_all: the trigram index on entity_alias needs the
        # extension to exist at CREATE INDEX time. Migration 0002 does the same
        # for databases that upgrade instead of being created.
        connection.execute(text("CREATE EXTENSION IF NOT EXISTS pg_trgm"))
    Base.metadata.create_all(engine)
    with Session(engine) as session, session.begin():
        seed_identifier_namespaces(session)
        seed_predicates(session)


def include_object(
    obj: Any, name: str, type_: str, reflected: bool, compare_to: Any
) -> bool:
    """Ignore anything this project did not declare.

    The database runs PostGIS, whose tiger geocoder installs some sixty tables
    of its own — `state`, `county_lookup`, `tabblock20` and the rest. Alembic
    reflects everything it finds, sees them missing from `Base.metadata`, and
    autogenerates DROP TABLE for each. Running that would take the extension
    apart.

    So autogenerate only considers objects we declared. Anything reflected from
    the database that is not in our metadata is somebody else's, and dropping
    somebody else's table is never what a migration of ours should do.

    Lives here rather than in alembic/env.py so the tests can import the filter
    that actually runs, instead of a copy of it that could drift.
    """

    if not reflected:
        return True
    if type_ == "table":
        return name in Base.metadata.tables
    # An index or constraint belongs to whichever table owns it.
    owner = getattr(obj, "table", None)
    if owner is not None:
        return owner.name in Base.metadata.tables
    return True


AUTOGENERATE_OPTIONS: dict[str, Any] = {
    "target_metadata": Base.metadata,
    "include_object": include_object,
    # Both off by default, and both are how a schema quietly drifts: a widened
    # VARCHAR or a changed server_default would otherwise never appear in an
    # autogenerated revision.
    "compare_type": True,
    "compare_server_default": True,
}
